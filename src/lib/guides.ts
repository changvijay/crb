import "server-only";
import { readFile } from "node:fs/promises";
import path from "node:path";
import type { Metadata } from "next";
import { cacheLife } from "next/cache";
import seo from "@/content/guides/seo.json";
import { META, pageMetadata, scrubLd } from "@/lib/seo";

type Seo = { title: string; description: string; keywords?: string | null; canonical: string; ogtitle?: string | null; ogdesc?: string | null; ld: string[] };
const SEO = seo as unknown as Record<string, Seo>;

export type TocItem = { id: string; label: string; part?: undefined } | { part: string; id?: undefined; label?: undefined };

const strip = (s: string) => s.replace(/<[^>]+>/g, "").replace(/&amp;/g, "&").replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&#39;/g, "'").replace(/&quot;/g, '"').replace(/\s+/g, " ").trim();

/** Sanitized first-party guide fragment, generated by scripts/extract-guide.py. */
export async function loadGuide(slug: string, headingTag = "h2"): Promise<{ html: string; toc: TocItem[] }> {
  "use cache";
  cacheLife("max"); // content only changes when the extraction script is re-run and the app rebuilt
  const html = await readFile(path.join(process.cwd(), "src/content/guides", `${slug}.html`), "utf8");
  let toc: TocItem[] = [];
  try {
    toc = JSON.parse(await readFile(path.join(process.cwd(), "src/content/guides", `${slug}.toc.json`), "utf8")) as TocItem[];
  } catch {
    /* no generated TOC: derive it from the headings below */
  }
  const re = new RegExp(`<${headingTag}[^>]*\\sid="([^"]+)"[^>]*>(.*?)</${headingTag}>`, "gs");
  if (!toc.length) for (const m of html.matchAll(re)) toc.push({ id: m[1], label: strip(m[2]) });
  return { html, toc };
}

export function guideMetadata(slug: string): Metadata {
  const s = SEO[slug];
  const path = new URL(s.canonical).pathname;
  // Titles and descriptions are authored once in lib/seo.ts; the extracted copy in seo.json is only a fallback.
  return META[path] ? pageMetadata(path) : { title: { absolute: s.title }, description: s.description, alternates: { canonical: s.canonical }, openGraph: { url: s.canonical, title: s.title, description: s.description } };
}

/** JSON-LD blocks exactly as authored on the original page. */
export function guideJsonLd(slug: string): unknown[] {
  return (SEO[slug]?.ld ?? []).flatMap((raw) => {
    try {
      return [scrubLd(JSON.parse(raw))];
    } catch {
      return [];
    }
  });
}
