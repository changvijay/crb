#!/usr/bin/env python3
"""
One-off content migration: reads a legacy HTML guide (read-only) and writes
  src/content/guides/<slug>.html   sanitized article fragment (verbatim text)
  src/content/guides/<slug>.css    the guide's own component CSS, scoped to .g-<slug>
                                   and re-pointed at the CRB theme tokens.
Usage: extract-guide.py <legacy.html> <slug> <content-selector-regex-start> [options as JSON]
"""
import json, re, sys, html as H
from pathlib import Path

SRC, SLUG = Path(sys.argv[1]), sys.argv[2]
CFG = json.loads(sys.argv[3]) if len(sys.argv) > 3 else {}
OUT = Path(__file__).resolve().parent.parent / "src" / "content" / "guides"
SCOPE = f".g-{SLUG}"

raw = SRC.read_text(encoding="utf-8")

# ── CSS ─────────────────────────────────────────────────────────────
css = "\n".join(re.findall(r"<style[^>]*>(.*?)</style>", raw, re.S))
css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
DROP = [re.compile(p) for p in CFG.get("drop_selectors", [])]

def find_close(s, i):
    d = 0
    for j in range(i, len(s)):
        if s[j] == "{": d += 1
        elif s[j] == "}":
            d -= 1
            if d == 0: return j
    return len(s) - 1

def scope_selector(sel):
    sel = sel.strip()
    if not sel: return None
    ta = CFG.get("theme_attr")
    tm = re.match(r'^(?::root)?\[data-theme="(\w+)"\]\s*(.*)$', sel)
    if ta and tm and tm.group(1) in ta:
        rest = tm.group(2).strip()
        return f'{SCOPE}[data-reader="{tm.group(1)}"]' + (f" {rest}" if rest else "")
    if any(p.search(sel) for p in DROP): return None
    m = re.match(r'^(html|body)?\s*(\[data-theme[^\]]*\])\s*(.*)$', sel)
    if m and m.group(2):
        rest = m.group(3).strip()
        return f'{m.group(2)} {SCOPE} {rest}'.strip() if rest else f'{m.group(2)} {SCOPE}'
    if re.match(r'^(:root|html|body)$', sel): return SCOPE
    if sel == "*" or sel in ("*, *::before, *::after", "*::before", "*::after"): return f"{SCOPE} *"
    if re.match(r'^(html|body)\b', sel): sel = re.sub(r'^(html|body)\s*', "", sel)
    return f"{SCOPE} {sel}"

def scope_block(block):
    out, pos = [], 0
    while pos < len(block):
        m = re.compile(r"\s*([^{};]+?)\s*\{").match(block, pos)
        if not m:
            nxt = block.find(";", pos)
            if nxt == -1: break
            seg = block[pos:nxt + 1].strip()
            if seg.startswith("@charset") or seg.startswith("@import"): pass
            pos = nxt + 1
            continue
        head = m.group(1).strip()
        end = find_close(block, m.end() - 1)
        inner = block[m.end():end]
        pos = end + 1
        if head.startswith("@keyframes") or head.startswith("@-webkit-keyframes"):
            out.append(f"{head}{{{inner}}}")
        elif head.startswith("@font-face"):
            continue
        elif head.startswith("@media") or head.startswith("@supports"):
            body = scope_block(inner)
            if body.strip(): out.append(f"{head}{{{body}}}")
        elif head.startswith("@"):
            continue
        else:
            sels = [scope_selector(x) for x in re.split(r",(?![^(]*\))", head)]
            sels = [x for x in sels if x]
            if sels: out.append(f"{', '.join(sels)}{{{inner}}}")
    return "\n".join(out)

root_vars = {}
for m in re.finditer(r"(?:^|\})\s*:root\s*\{([^}]*)\}", css):
    for k, v in re.findall(r"(--[\w-]+)\s*:\s*([^;]+);", m.group(1)): root_vars[k] = v.strip()
# remove :root blocks (we re-define the variables below)
css_wo_root = re.sub(r"(^|\})\s*:root\s*\{[^}]*\}", r"\1", css)
# fonts: never load Google fonts; point families at CRB fonts
scoped = scope_block(css_wo_root)

mapping = CFG.get("vars", {})
# Namespace the guide's own variables (--paper -> --g-paper) so mapping them onto CRB tokens can never self-reference.
def ns(text):
    for k in sorted(mapping, key=len, reverse=True):
        text = re.sub(r"var\(\s*" + re.escape(k) + r"(?![\w-])", f"var(--g-{k[2:]}", text)
        text = re.sub(r"(?<![\w-])" + re.escape(k) + r"(?=\s*:)", f"--g-{k[2:]}", text)  # declarations inside theme overrides
    return text
scoped = ns(scoped)
decl = "\n".join(f"  --g-{k[2:]}: {v};" for k, v in mapping.items())
extra = re.sub(r"crb\((--[\w-]+)\)", r"var(\1)", ns(CFG.get("extra_css", "")))
# Base rules sit BEFORE the guide's own CSS so its more specific selectors still win (Tailwind's reset removes list markers).
base = f"{SCOPE} ul{{list-style:disc}}\n{SCOPE} ol{{list-style:decimal}}\n{SCOPE} img{{max-width:100%;height:auto}}\n"
final = f"{SCOPE}{{background:transparent!important;margin:0!important}}\n{SCOPE} article{{margin-inline:auto}}\n"
(OUT / f"{SLUG}.css").write_text(f"/* Generated by scripts/extract-guide.py from the legacy {SRC.name}. Scoped to {SCOPE}. */\n{SCOPE} {{\n{decl}\n}}\n{base}{scoped}\n{final}{extra}\n", encoding="utf-8")

# ── HTML ────────────────────────────────────────────────────────────
body = raw[raw.find("<body"):]
body = re.sub(r"<script\b.*?</script>", "", body, flags=re.S | re.I)
body = re.sub(r"<style\b.*?</style>", "", body, flags=re.S | re.I)
body = re.sub(r"<!--.*?-->", "", body, flags=re.S)

start_pat = CFG.get("start")       # regex: first match is the start of the fragment
end_pat = CFG.get("end")           # regex: fragment ends before this match
if start_pat:
    m = re.search(start_pat, body, re.S)
    if not m: sys.exit(f"start pattern not found: {start_pat}")
    body = body[m.start():]
if end_pat:
    m = re.search(end_pat, body, re.S)
    if m: body = body[:m.start()]

for pat in CFG.get("remove", []):
    body = re.sub(pat, "", body, flags=re.S)
for pat, rep in CFG.get("replace", []):
    body = re.sub(pat, rep, body, flags=re.S)

# TOC (generated from the original sidebar so groups/labels stay exactly as authored)
toc_cfg = CFG.get("toc")
if toc_cfg:
    box = re.search(toc_cfg, raw, re.S)
    if box: box = re.search(r"(?s).*", re.sub(r"</span>\s*<span", "</span> <span", box.group(0)))
    items = []
    if box:
        for m in re.finditer(r'<div class="toc-part">(.*?)</div>|<a href="#([^"]+)"[^>]*>(.*?)</a>', box.group(0), re.S):
            if m.group(1) is not None: items.append({"part": H.unescape(re.sub(r"<[^>]+>", "", m.group(1))).strip()})
            else: items.append({"id": m.group(2), "label": H.unescape(re.sub(r"\s+", " ", re.sub(r"<[^>]+>", "", m.group(3)))).strip()})
    (OUT / f"{SLUG}.toc.json").write_text(json.dumps(items, ensure_ascii=False, indent=1), encoding="utf-8")

if CFG.get("toc_manual"):
    (OUT / f"{SLUG}.toc.json").write_text(json.dumps([{"id": i, "label": l} for i, l in CFG["toc_manual"]], ensure_ascii=False, indent=1), encoding="utf-8")

# inline style="...var(--x)..." references use the legacy names too
body = ns(body)

# sanitize
body = re.sub(r"\s+on[a-z]+\s*=\s*(\"[^\"]*\"|'[^']*')", "", body, flags=re.I)
body = re.sub(r"(href|src)\s*=\s*([\"'])\s*javascript:[^\"']*\2", r"\1=\2#\2", body, flags=re.I)
body = re.sub(r"<(iframe|object|embed|form|link|meta|base)\b[^>]*>(.*?</\1>)?", "", body, flags=re.S | re.I)
# internal links: drop .html, canonical map
LINKS = {"/PriceAction.html": "/price-action", "/Nifty_Equity_Indices.html": "/nifty-equity-indices"}
def fix_href(m):
    u = m.group(2)
    u = LINKS.get(u, u)
    if u.startswith("/") and u.endswith(".html"): u = u[:-5]
    return f'{m.group(1)}"{u}"'
body = re.sub(r'(href=)"([^"]*)"', fix_href, body)
body = re.sub(r"\n\s*\n+", "\n", body).strip()
(OUT / f"{SLUG}.html").write_text(body + "\n", encoding="utf-8")
print(f"{SLUG}: html {len(body)//1024}KB, css {len(scoped)//1024}KB, vars {len(mapping)}, root vars found {len(root_vars)}")
